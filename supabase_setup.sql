-- --------------------------------------------------------------------------
-- 1. TABELA DE CATEGORIAS
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  nome TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE
);

ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Leitura pública de categorias" ON public.categorias;
CREATE POLICY "Leitura pública de categorias" 
  ON public.categorias FOR SELECT 
  USING (true);

DROP POLICY IF EXISTS "Inserção pública de categorias" ON public.categorias;
CREATE POLICY "Inserção pública de categorias" 
  ON public.categorias FOR INSERT 
  WITH CHECK (true);

DROP POLICY IF EXISTS "Atualização pública de categorias" ON public.categorias;
CREATE POLICY "Atualização pública de categorias" 
  ON public.categorias FOR UPDATE 
  USING (true);

DROP POLICY IF EXISTS "Exclusão pública de categorias" ON public.categorias;
CREATE POLICY "Exclusão pública de categorias" 
  ON public.categorias FOR DELETE 
  USING (true);

